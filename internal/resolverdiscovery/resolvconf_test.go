package resolverdiscovery

import (
	"errors"
	"strings"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	body := `# Generated by NetworkManager
search lan example.net
nameserver 127.0.0.53
nameserver 9.9.9.9 # quad9
options edns0 trust-ad
; a legacy comment form
nameserver fe80::1%en0
nameserver not-an-address
nameserver
`
	got, err := ParseResolvConf(strings.NewReader(body))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"127.0.0.53", "9.9.9.9", "fe80::1%en0"}
	if len(got) != len(want) {
		t.Fatalf("%d addresses, want %d: %v", len(got), len(want), got)
	}
	for i, w := range want {
		if got[i].String() != w {
			t.Errorf("address %d is %s, want %s", i, got[i], w)
		}
	}
}

func TestParseResolvConfKeepsStubsForThePolicyToRefuse(t *testing.T) {
	// Parsing does not filter. On a systemd host the only entry is the stub,
	// and Choose is what turns that into ErrUnavailable — with the reason
	// Explain reports.
	got, err := ParseResolvConf(strings.NewReader("nameserver 127.0.0.53\n"))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 {
		t.Fatalf("%d addresses", len(got))
	}
	if _, err := Choose(got); !errors.Is(err, ErrUnavailable) {
		t.Errorf("Choose: %v", err)
	}
}

func TestParseResolvConfEmpty(t *testing.T) {
	got, err := ParseResolvConf(strings.NewReader(""))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 0 {
		t.Errorf("%d addresses from an empty file", len(got))
	}
}

// errReader fails after yielding its body, to check that a read error is
// reported rather than swallowed as a short file.
type errReader struct{ done bool }

func (e *errReader) Read(p []byte) (int, error) {
	if e.done {
		return 0, errors.New("read failed")
	}
	e.done = true
	return copy(p, "nameserver 9.9.9.9\n"), nil
}

func TestParseResolvConfReportsReadErrors(t *testing.T) {
	if _, err := ParseResolvConf(&errReader{}); err == nil {
		t.Error("read error swallowed")
	}
}
